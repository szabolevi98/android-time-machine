"""Generate Nougat Gboard 6.0.84 key rows and accent popups from angler's own compiled XML.
Requires the local image, aapt2 and androguard; writes ng-keyboard-data.js. No older keyboard data is used.
"""
import json, re, subprocess, sys, zipfile
sys.stdout.reconfigure(encoding='utf-8')
from pathlib import Path
from loguru import logger
logger.remove()
from androguard.core.axml import AXMLPrinter

ROOT = Path(__file__).resolve().parents[2]
APK = ROOT / '_aosp/angler/system/app/LatinIMEGooglePrebuilt/LatinIMEGooglePrebuilt.apk'
AAPT = 'D:/android_sdk/build-tools/36.0.0/aapt2.exe'
dump = subprocess.run([AAPT, 'dump', 'resources', str(APK)], capture_output=True, text=True, encoding='utf-8').stdout
ids = dict(re.findall(r'resource (0x[0-9a-f]+) (\S+)', dump))
z = zipfile.ZipFile(APK)

def ref(value):
    return ids.get(value.lower().replace('@', '0x'), value) if isinstance(value, str) else value

def xml(name):
    return AXMLPrinter(z.read('res/xml/' + name + '.xml')).get_xml_obj()

def attrs(e):
    return {k.split('}')[-1]: ref(v) for k, v in e.attrib.items()}

labels = {}
for name in z.namelist():
    if not name.startswith('res/xml/softkey') or not name.endswith('.xml'):
        continue
    for e in AXMLPrinter(z.read(name)).get_xml_obj().iter('softkey'):
        a = attrs(e)
        if a.get('press_data') and '$' not in a['press_data'] and not a['press_data'].startswith(('string/', 'array/')):
            labels[a.get('id')] = a['press_data']

layouts = {}
for lang, mapping in [('en', 'qwerty'), ('hu', 'qwertz'), ('de', 'qwertz'), ('fr', 'azerty'), ('es', 'spanish')]:
    group = next(e for e in xml('keymapping_' + mapping).iter('key_mapping') if not e.attrib.get('state'))
    rows = [{}, {}, {}]
    for e in group.iter('mapping'):
        a = attrs(e)
        hit = re.fullmatch(r'id/key_pos_([012])_(\d+)', a.get('view_id', ''))
        if not hit:
            continue
        key = a['key_id']
        label = labels.get(key)
        if label is None and re.fullmatch(r'id/softkey_latin_[a-z]', key):
            label = key[-1]
        if label is None:
            raise ValueError(f'{mapping}: no label for {key}')
        rows[int(hit[1])][int(hit[2])] = label
    accents = {}
    for e in xml('softkeys_input_' + lang).iter('softkey'):
        a = attrs(e)
        if 'press_data' in a and 'long_press_data' in a:
            accents[a['press_data']] = a['long_press_data'].split(',')
    layouts[lang] = {'rows': [[row[k] for k in sorted(row)] for row in rows], 'accents': accents,
                     'source': ['res/xml/keymapping_' + mapping + '.xml', 'res/xml/softkeys_input_' + lang + '.xml']}

def symbol_rows(secondary=False):
    rows = [{}, {}, {}]
    for name in ('keymapping_symbols_common', 'keymapping_symbols'):
        for group in xml(name).iter('key_mapping'):
            state = group.get('state', '')
            if state and (not secondary or state != 'SUB_CATEGORY_1'):
                continue
            for e in group.iter('mapping'):
                a = attrs(e)
                hit = re.fullmatch(r'id/key_pos_([012])_(\d+)', a.get('view_id', ''))
                if hit and a.get('key_id') in labels:
                    rows[int(hit[1])][int(hit[2])] = labels[a['key_id']]
    return [[row[k] for k in sorted(row)] for row in rows]

symbols = [symbol_rows(), symbol_rows(True)]
emoji = {}
for category in ('smiley_people', 'animals_nature', 'food_drink', 'activity', 'travel_places', 'objects', 'symbols', 'flags'):
    items = []
    for e in xml('softkeys_input_emoji_category_' + category).iter('softkey'):
        a = attrs(e)
        decode = lambda s: ''.join(chr(int(n, 16)) for n in re.findall(r'U\+([0-9A-Fa-f]+)', s))
        text = decode(a.get('param_data', ''))
        if text:
            items.append({'text': text, 'variants': [decode(v) for v in a.get('param_longpress_data', '').split()]})
    emoji[category] = items

head = '/* Generated by docs/tools/ng-keyboard-data.py from angler N2G48C LatinIMEGooglePrebuilt (Gboard 6.0.84). Do not edit. */\n'
defaults = {name: value == 'true' for name, value in re.findall(r'bool/pref_def_value_(\w+)[^\n]*\n\s+\(\) (true|false)', dump)}
(ROOT / 'versions/7.1.2/ng-keyboard-data.js').write_text(head + 'NG.keyboardData = ' + json.dumps(layouts, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8', newline='\n')
with (ROOT / 'versions/7.1.2/ng-keyboard-data.js').open('a', encoding='utf-8', newline='\n') as f:
    f.write('NG.keyboardSymbols = ' + json.dumps(symbols, ensure_ascii=False) + ';\n')
    f.write('NG.keyboardEmoji = ' + json.dumps(emoji, ensure_ascii=False) + ';\n')
    f.write('NG.keyboardDefaults = ' + json.dumps(defaults, ensure_ascii=False) + ';\n')
for lang, data in layouts.items():
    print(lang, [''.join(row) for row in data['rows']], len(data['accents']), 'accent popups')
print('symbols', symbols, 'emoji', {k: len(v) for k, v in emoji.items()})

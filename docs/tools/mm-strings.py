"""Android 6.0.1: generates the text tables versions/6.0.1/mm-strings-<table>.js from the Nexus 5X image (MTC20K).

    python docs/tools/mm-strings.py            (every table)
    python docs/tools/mm-strings.py shade      (one)

docs/data/mm-strings.txt lists the tables: a line "[table] Apk Apk …" starts one (the APKs as in the image, 'framework' =
framework-res.apk, tried in order), then resource names separated by spaces or newlines; "array:name" and "plurals:name"
take a string-array or a plurals resource (keyed "array:name" when a string of the table has its name), "Apk/name" reads a resource of that APK (the row is keyed Apk/name), and
"name+args<n>" marks a text the code formats with n arguments the English may not show, and "own:<key>" a text the image does not have, from docs/data/mm-own.tsv (<table> TAB <key> TAB <English> TAB <Hungarian>
TAB <German> TAB <French> TAB <Spanish> TAB <source>; an empty language is the English).
Unlike 2.1, 6.0.1 ships every language of the simulator itself, Hungarian included, so each row is the image's own text;
a language the image does not translate shows the English, as the phone does, and the row lists it as untranslated.
Each table is MM.strings('<table>', {name: {res, en, hu, de, fr, es, …}}). Do not edit the output by hand."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from image_res import ImageRes, ROOT
from era import DEVICE, BUILD, PHONE, JS, data, out

# The image of the version being built (docs/tools/era.py: ERA=mm 6.0.1, ERA=ng 7.1.2).
BULLHEAD = ImageRes(DEVICE)
LANGS = ('en', 'hu', 'de', 'fr', 'es')


def own_rows():
    rows = {}
    path = ROOT + data('own.tsv')
    if os.path.exists(path):
        for line in open(path, encoding='utf-8'):
            if line.strip() and not line.startswith('#'):
                table, key, en, hu, de, fr, es, source = line.rstrip('\n').split('\t')
                rows[(table, key)] = {'en': en, 'hu': hu, 'de': de, 'fr': fr, 'es': es, 'source': source}
    return rows


def tables():
    out, current = {}, None
    for line in open(ROOT + data('strings.txt'), encoding='utf-8'):
        line = line.split('#', 1)[0].strip()
        if not line: continue
        if line.startswith('['):
            name, *apks = line[1:].replace(']', ' ').split()
            current = out.setdefault(name, {'apks': apks, 'keys': []})
        else:
            current['keys'] += line.split()
    return out


def which_apk(apks, kind, key):
    for apk in apks:
        r, pkg, _ = BULLHEAD._apk(apk)
        if r.get_res_id_by_key(pkg, kind, key) is not None: return apk
    return None


def build(table, spec, own):
    entries = {}
    for item in spec['keys']:
        if item.startswith('own:'):
            key = item[4:]
            if (table, key) not in own: raise SystemExit(f'{table}: own:{key} is not in {data("own.tsv")}')
            o = own[(table, key)]
            row = {'own': True, 'source': o['source'], 'en': o['en']}
            gaps = [lang for lang in LANGS[1:] if not o[lang]]
            row.update({lang: o[lang] or o['en'] for lang in LANGS[1:]})
            if gaps: row['untranslated'] = gaps
            entries[key] = row
            continue
        # "name+args<n>": the code formats the text with n arguments even where the English has no placeholder for them.
        args = 0
        if '+args' in item: item, args = item.split('+args')[0], int(item.split('+args')[1])
        kind, key = item.split(':', 1) if ':' in item else ('string', item)
        name = key
        if '/' in key:
            hint, key = key.split('/', 1)
            apk = which_apk([hint], kind, key)
        else:
            apk = which_apk(spec['apks'], kind, key)
        if not apk: raise SystemExit(f'{table}: {kind} {key} is not in {spec["apks"]}')
        value = getattr(BULLHEAD, kind)([apk], key)
        row = {'res': f'{DEVICE}:{apk}:{key}', **({'args': args} if args else {})}
        row.update({lang: value[lang] for lang in LANGS if value.get(lang) is not None})
        if 'en' not in row:   # no default value the 5X reads (e.g. an array only some configurations define)
            print(f'{table}: {kind} {key} has no default value; left out'); continue
        gaps = [lang for lang in LANGS[1:] if lang not in row]
        for lang in gaps: row[lang] = row['en']
        if gaps: row['untranslated'] = gaps
        # A string-array or plurals named like a string of the table keeps its kind in its key ("array:wifi_signal").
        if kind != 'string' and name in entries: name = f'{kind}:{name}'
        entries[name] = row
    head = (f'/* Generated by docs/tools/mm-strings.py from the {PHONE} {BUILD} image ({", ".join(spec["apks"])}; en, hu, de, fr, es,\n'
            f'   every language the image\'s own). Do not edit. */\n')
    body = json.dumps(entries, ensure_ascii=False, indent=0)
    open(ROOT + out(f'strings-{table}.js'), 'w', encoding='utf-8', newline='\n').write(f"{head}{JS}.strings('{table}', {body});\n")
    untranslated = [k for k, r in entries.items() if r.get('untranslated')]
    print(f'{table}: {len(entries)} rows' + (f'; untranslated in the image: {untranslated}' if untranslated else ''))


if __name__ == '__main__':
    all_tables, own = tables(), own_rows()
    for name in sys.argv[1:] or list(all_tables):
        build(name, all_tables[name], own)

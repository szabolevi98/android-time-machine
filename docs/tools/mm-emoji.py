"""Android 6.0.1: Messenger's emoji keyboard (PrebuiltBugle's EmojiKeyboard) from the image.

    python -E docs/tools/mm-emoji.py

The APK lists each category's emoji as a string array of code points (emoji_faces, emoji_nature, emoji_objects,
emoji_places, emoji_symbols; a sequence joined by '_') and draws each one from its own 128 x 128 drawable-nodpi
emoji_u<code points>.png. Here each category becomes one sprite, versions/6.0.1/assets/bg-emoji-<category>.png (16 cells
a row, each scaled to 72 x 72, a 256-colour palette), and versions/6.0.1/mm-emoji.js gives MM.bugleEmoji = {category: [code points, ...]} in
the sprite's order. An emoji whose drawable is missing is left out, as the keyboard does."""
import glob, io, os, sys, zipfile
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from image_res import ImageRes

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
OUT = ROOT + 'versions/6.0.1/'
CATS = ['faces', 'nature', 'objects', 'places', 'symbols']
CELL, COLS = 72, 16

apk = glob.glob(ROOT + '_aosp/bullhead/system/*/PrebuiltBugle/PrebuiltBugle.apk')[0]
z = zipfile.ZipFile(apk)
files = {n.rsplit('/', 1)[1][len('emoji_u'):-4]: n for n in z.namelist() if '/emoji_u' in n and n.endswith('.png')}
res = ImageRes('bullhead')
out = {}
for cat in CATS:
    codes = [c for c in res.array(['PrebuiltBugle'], f'emoji_{cat}')['en'] if c in files]
    rows = (len(codes) + COLS - 1) // COLS
    sheet = Image.new('RGBA', (COLS * CELL, rows * CELL), (0, 0, 0, 0))
    for i, code in enumerate(codes):
        im = Image.open(io.BytesIO(z.read(files[code]))).convert('RGBA').resize((CELL, CELL), Image.LANCZOS)
        sheet.paste(im, ((i % COLS) * CELL, (i // COLS) * CELL))
    # The emoji drawables are 8-bit palette PNGs; a 256-colour palette per sheet keeps them as they look.
    sheet.quantize(256, method=Image.Quantize.FASTOCTREE).save(f'{OUT}assets/bg-emoji-{cat}.png', optimize=True)
    out[cat] = codes
    print(cat, len(codes))
body = ',\n'.join(f"  {cat}: '{' '.join(codes)}'.split(' ')" for cat, codes in out.items())
open(OUT + 'mm-emoji.js', 'w', encoding='utf-8', newline='\n').write(
    "/* Generated by docs/tools/mm-emoji.py from PrebuiltBugle's emoji_* arrays: each category's code points in the order of\n"
    "   its sprite (assets/bg-emoji-<category>.png, 16 cells a row). Do not edit. */\n"
    f"MM.bugleEmoji = {{\n{body}\n}};\nMM.bugleEmojiCols = {COLS};\n")

"""Android 6.0.1: writes versions/6.0.1/mm-domains.js, MM.appDomains = {app: [hosts]}: for each launcher app of the image
(mm-apps.js) the hosts of its http/https BROWSABLE intent filters in manifest order, the "supported links" Settings'
AppLaunchSettings lists (Utils.getHandledDomains).

    python docs/tools/mm-domains.py"""
import json, re, subprocess
A = 'D:/android_sdk/build-tools/36.0.0/aapt2.exe'
ROOT = 'D:/xampp/htdocs/android-simulator/'
SYS = ROOT + '_aosp/bullhead/system/'
apps = json.loads(re.search(r'MM\.appsData = (\{.*?\n\});', open(ROOT + 'versions/6.0.1/mm-apps.js', encoding='utf-8').read(), re.S).group(1))
out = {}
for id, a in apps.items():
    m = re.match(r'bullhead:(.*?\.apk)', a.get('res', ''))
    if not m: continue
    xml = subprocess.run([A, 'dump', 'xmltree', SYS + m.group(1), '--file', 'AndroidManifest.xml'], capture_output=True, text=True, encoding='utf-8', errors='replace').stdout
    hosts = []
    for f in re.split(r'E: intent-filter', xml)[1:]:
        f = re.split(r'E: (?:activity|activity-alias|service|receiver|provider)\b', f)[0]
        if 'android.intent.category.BROWSABLE' not in f: continue
        if not any(s in ('http', 'https') for s in re.findall(r'scheme\(0x01010027\)="([^"]+)"', f)): continue
        for h in re.findall(r'host\(0x01010028\)="([^"]+)"', f):
            if h not in hosts: hosts.append(h)
    if hosts: out[id] = hosts
body = ',\n'.join(f'{json.dumps(k)}: {json.dumps(v)}' for k, v in out.items())
head = ("/* Generated by docs/tools/mm-domains.py from the Nexus 5X MTC20K image: each launcher app's http/https BROWSABLE hosts\n"
        "   (AppLaunchSettings' supported links). Do not edit. */\n")
open(ROOT + 'versions/6.0.1/mm-domains.js', 'w', encoding='utf-8', newline='\n').write(head + 'MM.appDomains = {\n' + body + '\n};\n')
print(len(out), 'apps')

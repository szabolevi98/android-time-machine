"""Android 7.1.2: the system CA store of the Nexus 6P image (/system/etc/security/cacerts, N2G48C) for Settings'
TrustedCredentialsSettings, as android.net.http.SslCertificate reads each certificate.

    python -E docs/tools/ng-cacerts.py

Writes versions/7.1.2/ng-cacerts.js: NG.caCerts = [{alias, to: [CN, O, OU], by: [CN, O, OU], dname, serial, from, to_,
sha256, sha1}] in the store's file order. SslCertificate builds its DName from getSubjectDN().getName(), the RFC 2253
string (most specific attribute first), and keeps the first CN, O and OU it meets, so of repeated attributes the last
one of the DER sequence wins. serial, sha256 and sha1 are SslCertificate.fingerprint's upper-case hex pairs joined by
':' (the serial from BigInteger.toByteArray, sign byte included); from / to_ are the validity in ms since the epoch."""
import glob, hashlib, json, os
from cryptography import x509
from cryptography.x509.oid import NameOID

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))).replace(os.sep, '/') + '/'
STORE = ROOT + '_aosp/angler/system/etc/security/cacerts/'


def first(name, oid):
    for rdn in reversed(name.rdns):
        for a in rdn:
            if a.oid == oid: return a.value
    return ''


def hexpairs(b): return ':'.join(f'{x:02X}' for x in b)


def serial_bytes(n):
    length = n.bit_length() // 8 + 1
    return n.to_bytes(length, 'big', signed=True)


certs = []
for path in sorted(glob.glob(STORE + '*')):
    cert = x509.load_pem_x509_certificate(open(path, 'rb').read())
    der = cert.public_bytes(encoding=__import__('cryptography.hazmat.primitives.serialization', fromlist=['Encoding']).Encoding.DER)
    s, i = cert.subject, cert.issuer
    certs.append({'alias': 'system:' + os.path.basename(path),
                  'to': [first(s, NameOID.COMMON_NAME), first(s, NameOID.ORGANIZATION_NAME), first(s, NameOID.ORGANIZATIONAL_UNIT_NAME)],
                  'by': [first(i, NameOID.COMMON_NAME), first(i, NameOID.ORGANIZATION_NAME), first(i, NameOID.ORGANIZATIONAL_UNIT_NAME)],
                  'dname': s.rfc4514_string(),
                  'serial': hexpairs(serial_bytes(cert.serial_number)),
                  'from': int(cert.not_valid_before_utc.timestamp() * 1000), 'to_': int(cert.not_valid_after_utc.timestamp() * 1000),
                  'sha256': hexpairs(hashlib.sha256(der).digest()), 'sha1': hexpairs(hashlib.sha1(der).digest())})
out = ROOT + 'versions/7.1.2/ng-cacerts.js'
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by docs/tools/ng-cacerts.py from the N2G48C system CA store (/system/etc/security/cacerts).\n')
    f.write('NG.caCerts = ' + json.dumps(certs, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(certs), 'certificates,', os.path.getsize(out), 'bytes')

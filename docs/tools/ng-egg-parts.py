"""7.1.2: writes versions/7.1.2/ng-egg-parts.js, the inner markup of the Neko cat parts that docs/tools/mm-vectors.py drew
from EasterEgg.apk (versions/7.1.2/assets/egg-<part>.svg, docs/data/ng-vectors-egg.tsv), so ng-egg.js can tint and stack
them inside one self-contained SVG (an <img> of a data: SVG cannot load other files).

    python docs/tools/ng-egg-parts.py"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))) + '/'
PARTS = ['back', 'belly', 'body', 'bowtie', 'cap', 'collar', 'face_spot', 'foot1', 'foot2', 'foot3', 'foot4', 'head', 'left_ear',
         'left_ear_inside', 'left_eye', 'leg1', 'leg2', 'leg2_shadow', 'leg3', 'leg4', 'mouth', 'nose', 'right_ear',
         'right_ear_inside', 'right_eye', 'tail', 'tail_cap', 'tail_shadow']
out = {}
for p in PARTS:
    svg = open(f'{ROOT}versions/7.1.2/assets/egg-{p}.svg', encoding='utf-8').read()
    assert 'viewBox="0 0 48 48"' in svg, p
    inner = re.sub(r'<!--.*?-->', '', svg.split('>', 1)[1].rsplit('</svg>', 1)[0])
    # The part's own fills and strokes are replaced by the tint (Drawable.setTint is SRC_IN over the part's alpha).
    out[p] = re.sub(r' stroke="#[0-9a-f]{6}"', ' stroke="currentColor"', re.sub(r' fill="#[0-9a-f]{6}"', '', inner))
open(f'{ROOT}versions/7.1.2/ng-egg-parts.js', 'w', encoding='utf-8', newline='\n').write(
    '/* Generated by docs/tools/ng-egg-parts.py from the EasterEgg.apk cat parts (assets/egg-*.svg). Do not edit. */\n'
    f'NG.nekoParts = {json.dumps(out, separators=(",", ":"))};\n')
print(len(out), 'parts')

// Audit point 12: the fonts each version's stylesheets bind (@font-face: family, weight, style, file) against its factory
// image: a system font must be byte-identical to /system/fonts/<name> of that image (docs/tools/extract-image.py unpacks it), an
// app's own font to the file of that name inside one of the image's APKs. Writes docs/reports/font-check.md.
//     node docs/tools/font-check.mjs
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {inflateRawSync} from 'node:zlib';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '../..');
const DEVICES = {'2.1': 'passion', '2.3.6': 'crespo', '4.0.4': 'maguro', '4.3': 'mako', '4.4.4': 'hammerhead', '5.1.1': 'shamu', '6.0.1': 'bullhead', '7.1.2': 'angler'};
const hash = buf => createHash('sha1').update(buf).digest('hex');

// The entries of a zip (APK): name -> stored or deflated data, read from the central directory.
function zipEntries(file) {
  const buf = fs.readFileSync(file), out = new Map();
  let eocd = buf.length - 22; while (eocd > 0 && buf.readUInt32LE(eocd) !== 0x06054b50) eocd--;
  let p = buf.readUInt32LE(eocd + 16);
  for (let n = buf.readUInt16LE(eocd + 10); n > 0; n--) {
    const method = buf.readUInt16LE(p + 10), size = buf.readUInt32LE(p + 20), nameLen = buf.readUInt16LE(p + 28), extra = buf.readUInt16LE(p + 30), comment = buf.readUInt16LE(p + 32), local = buf.readUInt32LE(p + 42);
    const name = buf.toString('utf8', p + 46, p + 46 + nameLen);
    out.set(name, () => { const start = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28), data = buf.subarray(start, start + size); return method === 8 ? inflateRawSync(data) : data; });
    p += 46 + nameLen + extra + comment;
  }
  return out;
}
const apkFonts = new Map();
function appFonts(device) {
  if (apkFonts.has(device)) return apkFonts.get(device);
  const found = new Map(), walk = dir => { for (const f of fs.readdirSync(dir, {withFileTypes: true})) { const full = path.join(dir, f.name); if (f.isDirectory()) walk(full); else if (f.name.endsWith('.apk')) { try { for (const [name, read] of zipEntries(full)) if (/\.(ttf|otf)$/i.test(name)) found.set(`${path.basename(full, '.apk')}:${name}`, read); } catch {} } } };
  for (const top of ['app', 'priv-app']) { const dir = path.join(ROOT, '_aosp', device, 'system', top); if (fs.existsSync(dir)) walk(dir); }
  apkFonts.set(device, found); return found;
}

const out = ['# Font check', '', 'Generated by `docs/tools/font-check.mjs` (audit point 12): every @font-face of the stylesheets a version loads, against its factory image — /system/fonts for system fonts, the APKs for an app\'s own fonts.', ''];
let problems = 0;
for (const [version, device] of Object.entries(DEVICES)) {
  const page = fs.readFileSync(path.join(ROOT, 'versions', version, 'index.html'), 'utf8');
  const sheets = [...page.matchAll(/<link[^>]*href="([^"?]+\.css)/g)].map(m => path.posix.normalize(`versions/${version}/${m[1]}`));
  const faces = new Map();
  for (const sheet of sheets) {
    if (!fs.existsSync(path.join(ROOT, sheet))) continue;
    for (const m of fs.readFileSync(path.join(ROOT, sheet), 'utf8').matchAll(/@font-face\s*\{([^}]*)\}/g)) {
      const body = m[1], url = body.match(/url\(\s*['"]?([^'")]+)/)?.[1];
      if (!url) continue;
      const file = path.posix.normalize(path.posix.join(path.posix.dirname(sheet), url));
      const family = body.match(/font-family\s*:\s*['"]?([^;'"]+)/)?.[1], weight = body.match(/font-weight\s*:\s*([^;]+)/)?.[1]?.trim() || '400', style = body.match(/font-style\s*:\s*([^;]+)/)?.[1]?.trim() || 'normal';
      faces.set(`${family}|${weight}|${style}|${file}`, {family, weight, style, file, sheet});
    }
  }
  const fontsDir = path.join(ROOT, '_aosp', device, 'system', 'fonts');
  const system = fs.existsSync(fontsDir) ? fs.readdirSync(fontsDir) : [];
  out.push(`## ${version} (${device})`, '', `${faces.size} @font-face rules; ${system.length} files in the image's /system/fonts.`, '', '| Family | Weight / style | File | Image source | Result |', '| --- | --- | --- | --- | --- |');
  for (const {family, weight, style, file} of faces.values()) {
    const name = path.posix.basename(file).replace(/^(?:[a-z]{1,4}\d*-)+(?=[A-Z])/, ''), local = path.join(ROOT, file);
    let source = '—', result;
    if (!fs.existsSync(local)) result = 'missing in the repository';
    else if (system.includes(name)) { source = `/system/fonts/${name}`; result = hash(fs.readFileSync(local)) === hash(fs.readFileSync(path.join(fontsDir, name))) ? 'identical' : 'differs'; }
    else {
      const mine = hash(fs.readFileSync(local)), hit = [...appFonts(device)].find(([key, read]) => key.endsWith('/' + name) && hash(read()) === mine) || [...appFonts(device)].find(([, read]) => hash(read()) === mine);
      if (hit) { source = hit[0]; result = 'identical'; } else result = system.length ? 'not in this image' : 'image fonts not unpacked';
    }
    if (result !== 'identical') problems++;
    out.push(`| ${family} | ${weight} ${style} | \`${file.replace(`versions/${version}/`, '')}\` | ${source} | ${result} |`);
  }
  out.push('');
  console.log(version, faces.size, 'faces');
}
fs.writeFileSync(path.join(ROOT, 'docs', 'reports', 'font-check.md'), out.join('\n') + '\n');
console.log(problems, 'not identical (see docs/reports/font-check.md)');

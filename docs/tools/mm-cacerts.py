"""Writes versions/6.0.1/mm-cacerts.js: the system CA certificates of the Nexus 5X MTC20K image (/system/etc/security/
cacerts, unpacked in _aosp/bullhead/system) for Settings > Security > Trusted credentials, as MM.caCerts. The same reading
as docs/tools/lp-cacerts.py (TrustedCredentialsSettings.CertHolder's primary / secondary names, the list sorted on
them ignoring case; SslCertificate's issued to / by, validity and SHA-256 / SHA-1 fingerprints).
    python docs/tools/mm-cacerts.py"""
import hashlib, json, os, warnings
warnings.simplefilter('ignore')
from cryptography import x509
from cryptography.x509.oid import NameOID
from cryptography.hazmat.primitives.serialization import Encoding
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))).replace(os.sep, '/') + '/'
FOLDER = ROOT + '_aosp/bullhead/system/etc/security/cacerts/'


def part(name, oid):
    values = name.get_attributes_for_oid(oid)
    return values[0].value if values else ''


def names(name):
    return {'cn': part(name, NameOID.COMMON_NAME), 'o': part(name, NameOID.ORGANIZATION_NAME), 'ou': part(name, NameOID.ORGANIZATIONAL_UNIT_NAME)}


certs = []
for file in sorted(os.listdir(FOLDER)):
    data = open(FOLDER + file, 'rb').read()
    cert = x509.load_pem_x509_certificate(data[data.index(b'-----BEGIN CERTIFICATE-----'):])
    to, by = names(cert.subject), names(cert.issuer)
    if to['o']: primary, secondary = to['o'], to['cn'] or to['ou']
    elif to['cn']: primary, secondary = to['cn'], ''
    else: primary, secondary = cert.subject.rfc4514_string(), ''
    der = cert.public_bytes(Encoding.DER)
    digest = lambda h: ':'.join(f'{b:02X}' for b in h(der).digest())
    certs.append({'p': primary, 's': secondary, 'to': to, 'by': by,
                  'from': cert.not_valid_before_utc.strftime('%Y-%m-%d'), 'until': cert.not_valid_after_utc.strftime('%Y-%m-%d'),
                  'sha256': digest(hashlib.sha256), 'sha1': digest(hashlib.sha1), 'file': file})
certs.sort(key=lambda c: (c['p'].lower(), c['s'].lower()))
out = ('/* Generated by docs/tools/mm-cacerts.py from the Nexus 5X MTC20K image\'s /system/etc/security/cacerts. Do not edit. */\n'
       'MM.caCerts = ' + json.dumps(certs, ensure_ascii=False, separators=(',', ':')) + ';\n')
open(ROOT + 'versions/6.0.1/mm-cacerts.js', 'w', encoding='utf-8', newline='\n').write(out)
print(len(certs), 'certificates')

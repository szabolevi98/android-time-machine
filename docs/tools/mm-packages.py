"""Android 6.0.1: every package of the Nexus 5X MTC20K image for Settings' Apps list with Show system (ManageApplications
with every installed package): versions/6.0.1/mm-packages.js, MM.systemPackages = [{pkg, label: {en, hu, de, fr, es},
icon, size}] (the application label, falling back to the package name as PackageManager does; size: the APK and its
oat files), and docs/data/mm-assets-packages.tsv with each package's launcher icon (application android:icon) as
pk-<package>.png for docs/tools/mm-assets.py; a package without a bitmap icon shows the framework's sym_def_app_icon.
    python docs/tools/mm-packages.py
With ERA=ng (docs/tools/era.py) the same for 7.1.2 from the Nexus 6P N2G48C image: versions/7.1.2/ng-packages.js
(NG.systemPackages) and docs/data/ng-assets-packages.tsv."""
import glob, json, os, re, sys, zipfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from era import ERA, DEVICE, VERSION, BUILD, PHONE, JS
from loguru import logger; logger.remove()
from androguard.core.apk import APK

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))).replace(os.sep, '/') + '/'
SYSTEM = ROOT + f'_aosp/{DEVICE}/system/'
LANGS = ['en', 'hu', 'de', 'fr', 'es']
NS = '{http://schemas.android.com/apk/res/android}'
DENS = ['xxhdpi', 'xxxhdpi', 'xhdpi', 'hdpi', 'mdpi', 'nodpi', '']


def bitmap(z, kind, name):
    best = {}
    for p in z.namelist():
        m = re.match(rf'res/{kind}(?:-([a-z]+))?(?:-v\d+)?/{re.escape(name)}\.png$', p)
        if m and (m.group(1) or '') in DENS: best.setdefault(m.group(1) or '', p)
    return next((best[d] for d in DENS if d in best), None)


FW = APK(SYSTEM + 'framework/framework-res.apk').get_android_resources()
rows, assets = [], ['# Every package\'s launcher icon for Settings > Apps > Show system (written by docs/tools/mm-packages.py)']
paths = sorted(glob.glob(SYSTEM + 'app/**/*.apk', recursive=True) + glob.glob(SYSTEM + 'priv-app/**/*.apk', recursive=True)) + [SYSTEM + 'framework/framework-res.apk']
for path in paths:
    try: a = APK(path)
    except Exception: continue
    pkg = a.get_package()
    man = a.get_android_manifest_xml()
    appl = man.find('application')
    res = a.get_android_resources()
    label = {'en': pkg}
    ref = appl.get(NS + 'label') if appl is not None else None
    if ref and ref.startswith('@'):
        rid = int(ref.split(':')[-1].lstrip('@'), 16)
        try:
            for config, value in (FW if rid >> 24 == 1 else res).get_resolved_res_configs(rid):
                q = config.get_qualifier() or 'en'
                if q in LANGS and not str(value).startswith('<'): label[q] = value  # an unresolved reference stays the package name
        except Exception: pass
    elif ref and not ref.startswith('<'): label['en'] = ref
    label = {l: label.get(l, label['en']) for l in LANGS}
    size = os.path.getsize(path) + sum(os.path.getsize(f) for f in glob.glob(os.path.dirname(path) + '/oat/**/*', recursive=True) if os.path.isfile(f))
    icon = None
    iref = appl.get(NS + 'icon') if appl is not None else None
    if iref and iref.startswith('@') and pkg != 'android' and 'android:' not in iref:
        try:
            n = res.get_resource_xml_name(int(iref[1:], 16)).split(':')[-1].lstrip('@')
            kind, name = n.split('/', 1)
            if bitmap(zipfile.ZipFile(path), kind, name):
                icon = f'pk-{pkg}.png'
                assets.append(f'{icon}\t{os.path.relpath(path, SYSTEM).replace(os.sep, "/")}\t{kind}/{name}')
        except Exception: pass
    rows.append({'pkg': pkg, 'label': label, 'icon': f'assets/{icon}' if icon else 'assets/fw-sym_def_app_icon.png', 'size': size})
rows.sort(key=lambda r: r['label']['en'].lower())
head = (f'/* Generated by docs/tools/mm-packages.py from the {PHONE} {BUILD} image: every package with its label, icon and size\n'
        '   (Settings > Apps > Show system). Do not edit. */\n')
open(ROOT + f'versions/{VERSION}/{ERA}-packages.js', 'w', encoding='utf-8', newline='\n').write(head + f'{JS}.systemPackages = ' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n')
assets.append('fw-sym_def_app_icon.png\tframework/framework-res.apk\tmipmap/sym_def_app_icon')
open(ROOT + f'docs/data/{ERA}-assets-packages.tsv', 'w', encoding='utf-8', newline='\n').write('\n'.join(assets) + '\n')
print(len(rows), 'packages,', len(assets) - 2, 'icons')

"""Recover Photos 1.25's native CPE look catalogue and copy its LUT references.
The libnative.so constant table has 15 entries (None + 14 planet/moon looks).
"""
import hashlib,json,struct,zipfile
from pathlib import Path
from elftools.elf.elffile import ELFFile
import io
ROOT=Path(__file__).resolve().parents[2]
z=zipfile.ZipFile(ROOT/'_aosp/angler/system/app/Photos/Photos.apk')
b=z.read('lib/arm64-v8a/libnative.so');elf=ELFFile(io.BytesIO(b))
def cstring(offset):return b[offset:b.index(0,offset)].decode()
zero=b.index(b'0.png\0');section=elf.get_section_by_name('.data');data=section.data();offset=section['sh_offset']+data.index(struct.pack('<Q',zero));rows=[]
for i in range(15):
 file,name,color=struct.unpack_from('<QQI',b,offset+i*32)
 assert cstring(file)==str(i)+'.png'
 label=cstring(name).lower() if i else 'none'
 rows.append({'id':i,'label':'cpe_'+label+'_filter' if i else 'cpe_none_preset','asset':f'assets/ph-lut-{i}.png','color':f'#{color:06x}'})
result='/* Generated by docs/tools/ng-photos-presets.py from N2G48C Photos libnative.so catalogue / assets/luts. */\nNG.photoPresets = '+json.dumps(rows,indent=2)+';\n'
(ROOT/'versions/7.1.2/ng-photo-presets.js').write_text(result,encoding='utf-8')
print([(p['id'],p['label']) for p in rows]);print('native catalogue SHA-256',hashlib.sha256(b).hexdigest())

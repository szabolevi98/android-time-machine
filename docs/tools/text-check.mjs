// Audit point 10, the runtime check: each version is loaded in headless Chrome in every language, every app it lists
// is opened, and the keys the pages asked for but no table had (AndroidStrings.misses, AndroidI18n.misses) are written
// to docs/reports/text-check.md with the exceptions seen. Needs a server for the repository root (BASE, default
// http://localhost:8090, e.g. php -S localhost:8090 -t .) and Chrome.
//     node docs/tools/text-check.mjs [version...] [--langs hu,de,fr,es]
import {spawn} from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '../..');
const BASE = process.env.BASE || 'http://localhost:8090';
const CHROME = process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const args = process.argv.slice(2), at = args.indexOf('--langs');
const LANGS = at >= 0 ? args[at + 1].split(',') : ['hu', 'de', 'fr', 'es'];
const VERSIONS = args.filter((a, i) => /^\d/.test(a) && i !== at + 1);
const versions = VERSIONS.length ? VERSIONS : fs.readdirSync(path.join(ROOT, 'versions')).filter(v => /^\d/.test(v));
const sleep = ms => new Promise(r => setTimeout(r, ms));

// The app ids a version can open: data-app attributes and the [id, 'Label', …] rows of its app lists.
function apps(version) {
  const dir = path.join(ROOT, 'versions', version), ids = new Set();
  for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.js') || f.endsWith('.html'))) {
    const s = fs.readFileSync(path.join(dir, f), 'utf8');
    for (const m of s.matchAll(/data-app="([a-z0-9][a-z0-9-]+)"/g)) ids.add(m[1]);
    for (const m of s.matchAll(/\[\s*'([a-z][a-z0-9-]+)',\s*'[A-Z][^']*',/g)) ids.add(m[1]);
  }
  return [...ids].sort();
}

async function browser() {
  const port = 9300 + Math.floor(Math.random() * 500), dir = fs.mkdtempSync(path.join(os.tmpdir(), 'text-check-'));
  const proc = spawn(CHROME, ['--headless=new', `--remote-debugging-port=${port}`, `--user-data-dir=${dir}`, 'about:blank'], {stdio: 'ignore'});
  let ws;
  for (let i = 0; i < 120 && !ws; i++) { try { const page = (await (await fetch(`http://127.0.0.1:${port}/json`)).json()).find(t => t.type === 'page'); if (page) ws = new WebSocket(page.webSocketDebuggerUrl); } catch {} if (!ws) await sleep(250); }
  await new Promise(r => ws.onopen = r);
  let id = 0; const pending = {}, errors = [];
  ws.onmessage = m => { const d = JSON.parse(m.data); if (d.method === 'Runtime.exceptionThrown') errors.push(d.params.exceptionDetails.exception?.description?.split('\n')[0] || d.params.exceptionDetails.text); if (pending[d.id]) { pending[d.id](d); delete pending[d.id]; } };
  const send = (method, params = {}) => new Promise(r => { pending[++id] = r; ws.send(JSON.stringify({id, method, params})); });
  const ev = async expr => (await send('Runtime.evaluate', {expression: expr, awaitPromise: true, returnByValue: true})).result?.result?.value;
  await send('Runtime.enable');
  await send('Emulation.setDeviceMetricsOverride', {width: 420, height: 900, deviceScaleFactor: 1, mobile: false});
  return {send, ev, errors, close: () => { ws.close(); proc.kill(); }};
}

const report = {};
const b = await browser();
for (const version of versions) {
  const list = apps(version);
  for (const lang of LANGS) {
    b.errors.length = 0;
    await b.send('Page.navigate', {url: `${BASE}/versions/${version}/`}); await sleep(400);
    await b.ev(`localStorage.clear(); localStorage.setItem('android-time-machine-language', '${lang}')`);
    await b.send('Page.navigate', {url: `${BASE}/versions/${version}/`}); await sleep(2500);
    const click = (action, extra = '') => b.ev(`(()=>{const el=document.createElement('button');el.dataset.action=${JSON.stringify(action)};${extra}const host=document.querySelector('#viewport')?.firstElementChild||document.querySelector('#viewport');if(!host)return false;host.append(el);el.click();el.remove();return true})()`);
    for (const app of list) { await click('home'); await sleep(150); await click('open-app', `el.dataset.app=${JSON.stringify(app)};`); await sleep(500); }
    await click('home');
    const misses = await b.ev(`({strings: [...(window.AndroidStrings?.misses || [])], shared: [...(window.AndroidI18n?.misses || [])]})`);
    const r = report[version] ||= {apps: list.length, keys: new Map(), errors: new Set()};
    for (const [key] of [...(misses?.strings || []), ...(misses?.shared || [])]) r.keys.set(key, [...(r.keys.get(key) || []), lang]);
    for (const e of b.errors) r.errors.add(e);
    console.log(version, lang, list.length, 'apps,', (misses?.strings || []).length + (misses?.shared || []).length, 'missing keys,', b.errors.length, 'exceptions');
  }
}
b.close();
const out = ['# Text check — runtime', '', 'Generated by `docs/tools/text-check.mjs` (audit point 10): every app each version lists, opened in ' + LANGS.join(', ') + '; the keys a page asked a text table or the shared rows for without finding them, and the exceptions.', ''];
for (const [version, r] of Object.entries(report)) {
  out.push(`## ${version}`, '', `${r.apps} apps opened. ${r.keys.size} missing keys, ${r.errors.size} exceptions.`, '');
  for (const [key, langs] of [...r.keys].sort()) out.push(`- \`${key.replace(/`/g, "'").replace(/\n/g, ' ').slice(0, 120)}\` (${[...new Set(langs)].join(', ')})`);
  for (const e of r.errors) out.push(`- exception: ${e}`);
  out.push('');
}
const md = path.join(ROOT, 'docs', 'reports', 'text-check.md');
if (!VERSIONS.length || !fs.existsSync(md)) fs.writeFileSync(md, out.join('\n') + '\n');
else {
  // A run for some versions replaces their sections of the last report and keeps the others.
  let text = fs.readFileSync(md, 'utf8');
  for (const version of Object.keys(report)) {
    const section = out.join('\n').match(new RegExp(`## ${version.replace(/\./g, '\\.')}\\n[\\s\\S]*?(?=\\n## |$)`))[0];
    const existing = new RegExp(`## ${version.replace(/\./g, '\\.')}\\n[\\s\\S]*?(?=\\n## |$)`);
    text = existing.test(text) ? text.replace(existing, section.trimEnd() + '\n') : text.trimEnd() + '\n\n' + section.trimEnd() + '\n';
  }
  fs.writeFileSync(md, text);
}
console.log(out.join('\n'));

"""Android 7.1.2: the texts Chrome 55 keeps in its native locale packs (res/raw*/<locale>.lpak of the angler image's
Chrome.apk: the New Tab page's section headers, the network error page, the history page, the bookmark folders), for
versions/7.1.2/ng-strings-chromepak.js.

    python -E docs/tools/ng-chrome-pak.py                 the table
    python -E docs/tools/ng-chrome-pak.py --find <text>   the English strings containing <text>, with their ids

docs/data/ng-chrome-pak.txt lists "<key> TAB <English text>"; the text is looked up in en_us.lpak (pak format 4: version,
entry count, encoding, then id / offset pairs) and the same id is read from hu, de, fr and es. The packs use $1, $2 for
their arguments. The error page's icon is neterror.html's own (resources.pak: .icon-generic, the image set's 2x), as
NG.chromePakImages.generic. Do not edit the output."""
import json, os, re, struct, sys, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))).replace(os.sep, '/') + '/'
APK = ROOT + '_aosp/angler/system/app/Chrome/Chrome.apk'
PACKS = {'en': 'res/raw/en_us.lpak', 'hu': 'res/raw-hu/hu.lpak', 'de': 'res/raw-de/de.lpak', 'fr': 'res/raw-fr/fr.lpak', 'es': 'res/raw-es/es.lpak'}


def read(z, name):
    b = z.read(name)
    version, count, encoding = struct.unpack('<IIB', b[:9])
    assert version == 4, version
    entries = [struct.unpack('<HI', b[9 + i * 6: 15 + i * 6]) for i in range(count + 1)]
    out = {}
    for i in range(count):
        data = b[entries[i][1]:entries[i + 1][1]]
        out[entries[i][0]] = data.decode('utf-16-le' if encoding == 2 else 'utf-8', errors='replace')
    return out


z = zipfile.ZipFile(APK)
packs = {lang: read(z, path) for lang, path in PACKS.items()}
if len(sys.argv) > 2 and sys.argv[1] == '--find':
    for i, s in packs['en'].items():
        if sys.argv[2].lower() in s.lower(): print(i, repr(s[:160]))
    sys.exit()
rows = {}
for line in open(ROOT + 'docs/data/ng-chrome-pak.txt', encoding='utf-8'):
    if not line.strip() or line.startswith('#'): continue
    key, text = line.rstrip('\n').split('\t', 1)
    ids = [i for i, s in packs['en'].items() if s == text]
    if not ids: raise SystemExit(f'{key}: "{text}" is not in en_us.lpak')
    rows[key] = {'res': f'angler:Chrome:pak:{ids[0]}', **{lang: packs[lang].get(ids[0], packs['en'][ids[0]]) for lang in PACKS}}
body = json.dumps(rows, ensure_ascii=False, indent=0)
# neterror.html (the resource holding .icon-generic): its image set, the last (highest scale) data URI.
res = read(z, 'assets/resources.pak')
page = next(v for v in res.values() if '.icon-generic' in v and '<!doctype html>' in v[:20])
icon_set = re.search(r'\.icon-generic\s*\{.*?-webkit-image-set\((.*?)\);', page, re.S).group(1)
generic = re.findall(r'url\((data:image/png;base64,[A-Za-z0-9+/=]+)\)', icon_set)[-1]
open(ROOT + 'versions/7.1.2/ng-strings-chromepak.js', 'w', encoding='utf-8', newline='\n').write(
    '/* Generated by docs/tools/ng-chrome-pak.py from the Nexus 6P N2G48C image (Chrome 55\'s native locale packs; en, hu,\n'
    '   de, fr, es; the error page\'s icon from resources.pak). Do not edit. */\n' f"NG.strings('chromepak', {body});\n"
    f"NG.chromePakImages = {{generic: '{generic}'}};\n")
print(len(rows), 'rows')

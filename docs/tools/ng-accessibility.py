"""TalkBack 5.0.4 (N2G48C): tutorial catalogue and both native keyboard maps.

Uses only the angler APK and its OAT-derived classes. Prepare with oat2dex.py and
dex-decompile.py (KeyComboModelApp DefaultKeyComboModel), into
_aosp/angler/talkback-dex and _aosp/angler/talkback-java. --check compares outputs.
The small Java-to-JS translation below evaluates only getDefaultKeyComboCode's
constant decision tree; it does not execute an Android service.
"""
import hashlib, json, pathlib, re, subprocess, sys, zipfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
APK = ROOT / '_aosp/angler/system/app/talkback/talkback.apk'
maps = {}
for name, key in [('KeyComboModelApp', 'classic_keymap'), ('DefaultKeyComboModel', 'default_keymap')]:
    source = (ROOT / f'_aosp/angler/talkback-java/com.android.talkback.keyboard.{name}.java').read_text(encoding='utf-8')
    method = re.search(r'public long getDefaultKeyComboCode\(String (\w+)\)\s*(\{.*?\n    \})', source, re.S)
    param, body = method.groups()
    names = sorted(set(re.findall(r'R.string/(keycombo_shortcut_\w+)', body)))
    body = re.sub(r'this.mContext.getString\(R.string/(\w+)\{[^}]*\}\)', lambda m: json.dumps(m[1]), body)
    body = re.sub(r'!'+param+r'\.equals\(("[^"]+")\)', lambda m: f'{param} !== {m[1]}', body)
    body = re.sub(param+r'\.equals\(("[^"]+")\)', lambda m: f'{param} === {m[1]}', body)
    body = re.sub(r'\blong\b', 'var', body)
    body = re.sub(r'com.android.talkback.keyboard.\w+.IS_IN_ARC', 'false', body)
    body = re.sub(r'com.android.talkback.KeyComboManager.getKeyComboCode\((\d+), (\d+)\)', r'[\1,\2]', body)
    script = 'const fn=new Function('+json.dumps(param)+','+json.dumps(body)+');process.stdout.write(JSON.stringify(Object.fromEntries('+json.dumps(names)+'.map(k=>[k,fn(k)]))));'
    maps[key] = json.loads(subprocess.check_output(['node'], input=script, text=True))

with zipfile.ZipFile(APK) as z:
    tutorial = json.loads(z.read('res/raw/tutorial.json'))['lessons']
data = {'apkSha256': hashlib.sha256(APK.read_bytes()).hexdigest(), 'keymaps': maps, 'lessons': tutorial}
result = '/* Generated by docs/tools/ng-accessibility.py from angler N2G48C talkback.apk and its own OAT. Do not edit. */\nNG.accessibilityData = '+json.dumps(data, ensure_ascii=False, separators=(',', ':'))+';\n'
out = ROOT / 'versions/7.1.2/ng-accessibility-data.js'
if '--check' in sys.argv:
    if out.read_text(encoding='utf-8') != result: raise SystemExit('Accessibility data differs')
else:
    out.write_text(result, encoding='utf-8', newline='\n')
print(f'{len(tutorial)} lessons; '+', '.join(f'{k}: {len(v)} shortcuts' for k, v in maps.items()))

/* Google Maps 6.14.4 settings and My Places (Nexus 4 JWR66Y).
   Generated by docs/tools/maps-prefs.py from docs/templates/maps-prefs.template.js; each version styles the mps-
   classes in its own CSS. The screens are a stack (ui.mapsPrefs); values live in data.mapsPrefs, the home and work
   addresses in data.mapsHome / data.mapsWork, the searches of Maps history in data.mapsHistory (newest first).
   Rows whose page is Google's (help, feedback, offers, the web's terms) keep the simulator's generic limit. */
(() => {
  'use strict';
  const e = value => String(value ?? '').replace(/[&<>"']/g, c => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'}[c]));
  const lang = ctx => String(ctx.locale || ctx.lang || 'en').slice(0, 2);
  // The Maps APK's own texts (stock-strings.js, group maps); ownText rows are the simulator's (i18n.js).
  const S = (ctx, key) => { const row = window.StockStrings?.maps?.[key]; return row ? AndroidStrings.pick(row, lang(ctx), key) : ctx.t(key); };
  // Maps' texts use both MessageFormat's {0} and Android's %1$s.
  const fmt = (text, ...args) => AndroidStrings.format(args.reduce((s, a, i) => s.split(`{${i}}`).join(a), text), ...args);
  const value = (ctx, key, def) => ctx.data.mapsPrefs?.[key] ?? def;
  /* Maps 6.14.4 (mako JWR66Y): Settings is new_settings_preference.xml. Of its rows the local ones are drawn: Switch
     account (the one account), Cache settings (map_tile_settings.xml: Use cached tiles only and Clear cache, which empties
     the tiles the map has shown and has nothing to clear until the map is shown again) and About. Sign in, Location
     settings (Latitude's server settings), Labs (a server list), What's new, Legal, Feedback stay out like Latitude's
     list item, their titles being server text too. */
  const VERSION = '6.14.4';
  const DELETE_TITLE = ctx => S(ctx, 'Delete'), DELETE_MESSAGE = ctx => S(ctx, '<b>{0}</b> will be removed from My Places.');
  const SCREENS = {
    settings: ctx => ({title: S(ctx, 'Settings'), rows: [
      {kind: 'info', title: ctx.t('Switch account'), summary: ctx.account},
      {open: 'cache', title: ctx.t('Cache settings')},
      {kind: 'info', title: ctx.t('About'), summary: VERSION}]}),
    cache: ctx => ({title: ctx.t('Cache settings'), rows: [
      {kind: 'check', key: 'map_tile_settings_use_cached_tiles_only', title: ctx.t('Use cached tiles only'), def: false},
      {key: 'clear', title: ctx.t('Clear cache'), disabled: !ctx.data.mapsCache}]}),
    // My Places (MY_PLACES_COMMAND): the starred places (MY_PLACES_ITEM_IS_STARRED), a tap shows one on the map, × deletes
    // it after MY_PLACES_DELETE_CONFIRM; none gives MY_PLACES_NO_STARRED_ITEM_MESSAGE.
    places: ctx => ({title: S(ctx, 'My Places'), rows: (ctx.data.mapsStarred || []).length ? ctx.data.mapsStarred.map((q, i) => ({kind: 'item', key: `s:${i}`, del: `mapsStarred:${i}`, title: q, summary: S(ctx, 'Starred')})) : [{kind: 'empty', title: S(ctx, 'You have no starred places.')}]})
  };
  function act(key, ctx) {
    if (key === 'clear') { ctx.data.mapsCache = false; ctx.save(); return true; }
    if (key.startsWith('s:')) { const q = ctx.data.mapsStarred?.[Number(key.slice(2))]; ctx.ui.mapsPrefs = null; ctx.ui.mapsQuery = q || ''; return true; }
    return true;
  }
  const top = ui => (ui.mapsPrefs || []).at(-1);
  function row(ctx, r) {
    if (r.kind === 'empty') return `<p class="mps-empty">${e(r.title)}</p>`;
    const check = r.kind === 'check' ? `<i class="mps-check${value(ctx, r.key, r.def) ? ' on' : ''}" role="presentation"></i>` : '';
    const action = r.remote ? 'sa-unsupported' : r.kind === 'check' ? 'mps-check' : r.kind === 'list' ? 'mps-list' : r.open ? 'mps-open' : r.kind === 'info' ? '' : 'mps-act';
    const id = r.open || r.key || '';
    const text = `<span><b>${e(r.title)}</b>${r.summary ? `<small>${e(r.summary)}</small>` : ''}</span>`;
    const attrs = `${action ? ` data-action="${action}"` : ''}${id ? ` data-id="${e(id)}"` : ''}${r.kind === 'check' ? ` role="checkbox" aria-checked="${!!value(ctx, r.key, r.def)}"` : ''}${r.disabled ? ' disabled' : ''}`;
    if (r.kind === 'item') return `<div class="mps-row mps-item"><button class="mps-main" data-action="mps-act" data-id="${e(id)}">${text}</button><button class="mps-del" data-action="mps-del" data-id="${e(r.del)}" aria-label="${e(DELETE_TITLE(ctx))}">×</button></div>`;
    return `<button class="mps-row${r.kind === 'info' ? ' mps-info' : ''}${r.disabled ? ' disabled' : ''}"${attrs}>${text}${check}</button>`;
  }
  // ListPreference (radio list with Cancel), the address editor and Maps history's delete confirmation.
  function dialog(ctx, s) {
    const d = ctx.ui.mpsDialog; if (!d) return '';
    const shell = (title, body, buttons) => `<button class="mps-scrim" data-action="mps-cancel" aria-label="${e(S(ctx, 'Cancel'))}"></button><div class="mps-dialog" role="dialog" aria-label="${e(title)}"><h3>${e(title)}</h3>${body}${buttons ? `<div class="mps-buttons">${buttons}</div>` : ''}</div>`;
    if (d.kind === 'list') {
      const r = s.rows.find(x => x.key === d.key); if (!r) return '';
      const current = value(ctx, r.key, r.def);
      return shell(r.title, `<div class="mps-choices">${r.options.map((label, i) => `<button data-action="mps-pick" data-id="${e(r.key)}:${i}" role="radio" aria-checked="${r.values[i] === current}"><span>${e(label)}</span><i class="mps-radio${r.values[i] === current ? ' on' : ''}"></i></button>`).join('')}</div>`, `<button data-action="mps-cancel">${e(S(ctx, 'Cancel'))}</button>`);
    }
    if (d.kind === 'edit') return shell(d.title, `<input data-mps-input autocomplete="off" placeholder="${e(d.hint)}" value="${e(d.value || '')}">`, `<button data-action="mps-cancel">${e(S(ctx, 'Cancel'))}</button><button data-action="mps-edit-ok">${e(S(ctx, 'OK'))}</button>`);
    if (d.kind === 'delete') return shell(DELETE_TITLE(ctx), `<p>${fmt(e(DELETE_MESSAGE(ctx, d.store)).replace(/&lt;(\/?)b&gt;/g, '<$1b>'), e(ctx.data[d.store]?.[d.index] || ''))}</p>`, `<button data-action="mps-cancel">${e(S(ctx, 'Cancel'))}</button><button data-action="mps-del-ok">${e(DELETE_TITLE(ctx))}</button>`);
    return '';
  }
  function render(ctx) {
    const screen = SCREENS[top(ctx.ui)]; if (!screen) return '';
    const s = screen(ctx);
    return `<div class="app-view sa-app mps mps-${e(top(ctx.ui))}">${ctx.bar(s.title)}<div class="sa-scroll mps-list">${s.rows.map(r => row(ctx, r)).join('')}</div>${dialog(ctx, s)}</div>`;
  }
  const rowOf = (ctx, key) => SCREENS[top(ctx.ui)]?.(ctx).rows.find(r => (r.open || r.key) === key);
  // ctx: {ui, data, t, lang, locale, save, render, open(app, sub)}.
  function handle(action, id, ctx) {
    const {ui, data} = ctx, prefs = () => (data.mapsPrefs ||= {});
    switch (action) {
      case 'mps-settings': ui.mapsPanel = false; ui.overlay = ''; ctx.renderOverlay?.(); ui.mapsPrefs = [id || 'settings']; ui.mpsDialog = null; break;
      case 'mps-open': (ui.mapsPrefs ||= []).push(id); break;
      case 'mps-check': { const r = rowOf(ctx, id); if (!r) return true; prefs()[id] = !value(ctx, id, r.def); ctx.save(); break; }
      case 'mps-list': ui.mpsDialog = {kind: 'list', key: id}; break;
      case 'mps-pick': { const [key, i] = String(id).split(':'), r = rowOf(ctx, key); if (r) { prefs()[key] = r.values[Number(i)]; ctx.save(); } ui.mpsDialog = null; break; }
      case 'mps-cancel': ui.mpsDialog = null; break;
      case 'mps-edit-ok': { const d = ui.mpsDialog, input = document.querySelector('[data-mps-input]'); if (d && input) { data[d.store] = input.value.trim().slice(0, 120); ctx.save(); } ui.mpsDialog = null; break; }
      // An item's delete: "store:index" of the list it is in (data.mapsHistory, data.mapsStarred).
      case 'mps-del': { const [store, i] = String(id).split(':'); ui.mpsDialog = {kind: 'delete', store, index: Number(i)}; break; }
      case 'mps-del-ok': { const d = ui.mpsDialog; if (d && Array.isArray(data[d.store])) { data[d.store].splice(d.index, 1); ctx.save(); } ui.mpsDialog = null; break; }
      // The search card's star: the place joins (or leaves) the starred list.
      case 'mps-star': { const q = String(id || ''); if (!q) return true; const list = data.mapsStarred ||= []; const i = list.indexOf(q); if (i >= 0) list.splice(i, 1); else list.unshift(q); ctx.save(); break; }
      case 'mps-act': if (!act(id, ctx)) return true; break;
      default: return false;
    }
    ctx.render();
    if (ui.mpsDialog?.kind === 'edit') requestAnimationFrame(() => document.querySelector('[data-mps-input]')?.focus());
    return true;
  }
  // Back: the open dialog, then the screen under it, then the map.
  function back(ui) {
    if (!ui.mapsPrefs?.length) return false;
    if (ui.mpsDialog) ui.mpsDialog = null; else { ui.mapsPrefs.pop(); if (!ui.mapsPrefs.length) ui.mapsPrefs = null; }
    return true;
  }
  // A search to keep in Maps history: newest first, once, at most 20.
  function remember(data, query) { const q = String(query || '').trim(); if (!q) return; data.mapsHistory = [q, ...(data.mapsHistory || []).filter(x => x !== q)].slice(0, 20); }
  // The distance units: the saved choice, else the language's (the maps strings' "imperial" row).
  const imperial = (data, auto) => { const u = data?.mapsPrefs?.distance_units; return u === 'MILES' ? true : u === 'KILOMETERS' ? false : auto; };
  window.MapsPrefs = {render, handle, back, remember, imperial, active: ui => !!ui.mapsPrefs?.length};
})();
